async function deliverSupportNotifications() {
  if (supportNotificationCheck) return supportNotificationCheck;
  supportNotificationCheck = (async function () {
    try {
      const deviceToken = supportDeviceToken();
      const result = await api("/api/notifications/pending", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ deviceToken }) });
      const notifications = result.notifications || [];
      if (!notifications.length) return;
      const reportIds = notifications.map(function (notification) { return notification.reportId; });
      const message = notifications.some(function (notification) { return notification.kind === "reply"; })
        ? words().supportReplyForYou
        : reportIds.length === 1
        ? words().supportClosedForYou
        : words().supportClosedForYouMultiple.replace("{count}", String(reportIds.length));
      celebrateSuccess(message);
      await api("/api/notifications/ack", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ reportIds, deviceToken }) });
    } catch (error) {}
  })();
  return supportNotificationCheck;
}

function supportDeviceToken() {
  try {
    let token = localStorage.getItem("repairly-support-device");
    if (!token) {
      const bytes = new Uint8Array(32);
      window.crypto.getRandomValues(bytes);
      token = Array.from(bytes, function (byte) { return byte.toString(16).padStart(2, "0"); }).join("");
      localStorage.setItem("repairly-support-device", token);
    }
    return token;
  } catch (error) { return ""; }
}

