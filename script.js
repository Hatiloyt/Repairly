function unlockSuccessAudio() {
  if (!(window.AudioContext || window.webkitAudioContext)) return;
  const AudioContextType = window.AudioContext || window.webkitAudioContext;
  try {
    if (!successAudioContext) successAudioContext = new AudioContextType();
    document.removeEventListener("pointerdown", unlockSuccessAudio);
    document.removeEventListener("keydown", unlockSuccessAudio);
    const resumed = successAudioContext.state === "suspended" ? successAudioContext.resume() : Promise.resolve();
    if (pendingSuccessSound) resumed.then(function () { if (pendingSuccessSound) playSuccessSound(); }).catch(function () {});
  } catch (error) { successAudioContext = null; }
}

document.addEventListener("pointerdown", unlockSuccessAudio, { once: true, passive: true });
document.addEventListener("keydown", unlockSuccessAudio, { once: true });

function playSuccessSound() {
  const audio = successAudioContext;
  if (!audio || audio.state !== "running") { pendingSuccessSound = true; return; }
  pendingSuccessSound = false;
  const now = audio.currentTime;
  const notes = [659.25, 880];
  notes.forEach(function (frequency, index) {
    const oscillator = audio.createOscillator();
    const gain = audio.createGain();
    const startAt = now + index * 0.105;
    oscillator.type = "sine";
    oscillator.frequency.setValueAtTime(frequency, startAt);
    oscillator.frequency.exponentialRampToValueAtTime(frequency * 1.18, startAt + 0.16);
    gain.gain.setValueAtTime(0.0001, startAt);
    gain.gain.exponentialRampToValueAtTime(0.045, startAt + 0.025);
    gain.gain.exponentialRampToValueAtTime(0.0001, startAt + 0.24);
    oscillator.connect(gain);
    gain.connect(audio.destination);
    oscillator.start(startAt);
    oscillator.stop(startAt + 0.25);
  });
}

function launchConfetti() {
  const canvas = document.getElementById("success-confetti");
  if (!canvas || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  if (confettiFrame) window.cancelAnimationFrame(confettiFrame);
  const context = canvas.getContext("2d");
  if (!context) return;
  const width = window.innerWidth;
  const height = window.innerHeight;
  const ratio = Math.min(window.devicePixelRatio || 1, 2);
  canvas.width = Math.round(width * ratio);
  canvas.height = Math.round(height * ratio);
  canvas.hidden = false;
  context.setTransform(ratio, 0, 0, ratio, 0, 0);
  const palette = ["#82bb66", "#d9e9bd", "#e7b85e", "#5b7550", "#f5efe0"];
  const pieces = Array.from({ length: 105 }, function () {
    return {
      x: width * (0.12 + Math.random() * 0.76), y: -20 - Math.random() * height * 0.3,
      vx: (Math.random() - 0.5) * 5, vy: 2 + Math.random() * 4,
      spin: (Math.random() - 0.5) * 0.22, angle: Math.random() * Math.PI,
      size: 4 + Math.random() * 5, color: palette[Math.floor(Math.random() * palette.length)]
    };
  });
  const draw = function () {
    context.clearRect(0, 0, width, height);
    pieces.forEach(function (piece) {
      piece.x += piece.vx;
      piece.y += piece.vy;
      piece.vy += 0.075;
      piece.angle += piece.spin;
      context.save();
      context.translate(piece.x, piece.y);
      context.rotate(piece.angle);
      context.fillStyle = piece.color;
      context.fillRect(-piece.size / 2, -piece.size / 2, piece.size, piece.size * 0.62);
      context.restore();
    });
    if (pieces.some(function (piece) { return piece.y < height + 20; })) {
      confettiFrame = window.requestAnimationFrame(draw);
    } else {
      confettiFrame = 0;
      canvas.hidden = true;
      context.clearRect(0, 0, width, height);
    }
  };
  confettiFrame = window.requestAnimationFrame(draw);
}

