function renderRepairs() {
  if (!repairList) return;
  const query = repairSearch.value.trim().toLocaleLowerCase(root.lang);
  const filtered = repairs.filter(function (repair) {
    return [repair.title, repair.vehicle, categoryName(repair.category), difficultyName(repair.difficulty), repair.summary, repair.authorName, ...(repair.steps || [])].join(" ").toLocaleLowerCase(root.lang).includes(query);
  });
  if (currentUser && feedMode === "for-you") {
    filtered.sort(function (a, b) { return recommendationScore(b) - recommendationScore(a) || b.createdAt.localeCompare(a.createdAt); });
  } else {
    filtered.sort(function (a, b) { return b.createdAt.localeCompare(a.createdAt); });
  }
  repairList.replaceChildren();
  filtered.forEach(function (repair) {
    const card = document.createElement("article");
    card.id = "repair-" + repair.id;
    const matched = vehicleMatchScore(repair) > 0;
    card.className = "repair-card" + (currentUser && feedMode === "for-you" && matched ? " is-recommended" : "");
    const meta = document.createElement("div");
    meta.className = "repair-meta";
    addText(meta, "span", "repair-category", repair.isSample ? words().communitySample : categoryName(repair.category));
    if (currentUser && feedMode === "for-you" && matched) addText(meta, "span", "recommendation-label", words().forVehicle);
    addText(meta, "span", "repair-difficulty", difficultyName(repair.difficulty));
    if ((repair.confirmations || 0) >= 10) addText(meta, "span", "repair-badge", words().verifiedBadge);
    if (repair.adminVerified) addText(meta, "span", "repair-badge admin-verified-badge", words().adminVerifiedBadge);
    const coverImageData = repair.stepImages?.find(Boolean);
    if (coverImageData) {
      const cover = document.createElement("figure");
      cover.className = "repair-cover";
      const image = document.createElement("img");
      image.className = "repair-cover-image";
      image.src = coverImageData;
      image.alt = repair.title + (root.lang === "en" ? " cover photo" : " – Vorschaubild");
      image.loading = "lazy";
      cover.appendChild(image);
      card.appendChild(cover);
    }
    card.appendChild(meta);
    addText(card, "h3", "", repair.title);
    addText(card, "p", "repair-vehicle", repair.vehicle);
    addText(card, "p", "repair-summary", repair.summary);
    const details = document.createElement("details");
    const summary = document.createElement("summary");
    summary.textContent = words().openSteps + " · " + repair.steps.length + " " + words().stepsCount;
    details.appendChild(summary);
    const list = document.createElement("ol");
    list.className = "repair-steps";
    repair.steps.forEach(function (step, index) {
      const item = addText(list, "li", "", step);
      const imageData = repair.stepImages?.[index];
      if (imageData) {
        const image = document.createElement("img");
        image.className = "repair-step-image";
        image.src = imageData;
        image.alt = (root.lang === "en" ? "Photo for step " : "Bild zu Schritt ") + String(index + 1);
        image.loading = "lazy";
        item.appendChild(image);
      }
    });
    details.appendChild(list);
    card.appendChild(details);
    if ((repair.parts || []).length) {
      const partLinks = document.createElement("div");
      partLinks.className = "repair-parts";
      repair.parts.forEach(function (part, index) {
        const link = document.createElement("a");
        link.href = part.url;
        link.target = "_blank";
        link.rel = "noopener noreferrer";
        link.textContent = part.label || words().partsCount + " " + (index + 1);
        partLinks.appendChild(link);
      });
      card.appendChild(partLinks);
    }
    const footer = document.createElement("div");
    footer.className = "repair-foot";
    const count = repair.confirmations || 0;
    const confirmationWord = count === 1 ? words().confirmationSingular : words().confirmations;
    const author = document.createElement("span");
    author.className = "repair-author";
    addText(author, "span", "", words().author + " ");
    if (!repair.isSample && repair.authorId) {
      const authorLink = document.createElement("button");
      authorLink.type = "button";
      authorLink.className = "repair-author-link";
      authorLink.dataset.userProfile = repair.authorId;
      authorLink.textContent = repair.authorName;
      author.appendChild(authorLink);
    } else addText(author, "span", "", repair.authorName);
    addText(author, "span", "", " · " + count + " " + confirmationWord);
    footer.appendChild(author);
    const actions = document.createElement("div");
    actions.className = "repair-action-group";
    if (!repair.isSample) {
      const like = document.createElement("button");
      like.type = "button";
      like.className = "repair-like-button" + (repair.likedByMe ? " is-liked" : "");
      like.setAttribute("aria-pressed", String(Boolean(repair.likedByMe)));
      like.setAttribute("aria-label", (repair.likedByMe ? words().unlikeGuide : words().likeGuide) + " · " + (repair.likes || 0));
      const likeIcon = addText(like, "span", "", repair.likedByMe ? "♥" : "♡");
      likeIcon.setAttribute("aria-hidden", "true");
      addText(like, "span", "", String(repair.likes || 0));
      like.disabled = Boolean(repair.isOwn);
      like.addEventListener("click", async function () {
        if (!currentUser) { setAuthMode("login"); accountDialog.showModal(); return; }
        like.disabled = true;
        try {
          const result = await api("/api/repairs/" + encodeURIComponent(repair.id) + "/like", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" });
          repairs = repairs.map(function (item) { return item.id === repair.id ? result.repair : item; });
          renderRepairs();
        } catch (error) { like.disabled = false; showToast(friendlyError(error), "error"); }
      });
      actions.appendChild(like);
    }
    const verify = document.createElement("button");
    verify.type = "button";
    verify.className = "verify-button";
    const hasConfirmed = Boolean(currentUser && repair.confirmedByMe);
    const isOwn = Boolean(currentUser && repair.isOwn);
    const verifyLabel = hasConfirmed ? words().verified : !currentUser ? words().loginToVerify : isOwn ? words().ownRepair : words().verify;
    const verifyIcon = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    verifyIcon.setAttribute("viewBox", "0 0 20 20");
    verifyIcon.setAttribute("aria-hidden", "true");
    const verifyPath = document.createElementNS("http://www.w3.org/2000/svg", "path");
    verifyPath.setAttribute("d", "m4 10 4 4 8-8");
    verifyIcon.appendChild(verifyPath);
    const verifyText = document.createElement("span");
    verifyText.textContent = verifyLabel;
    verify.append(verifyIcon, verifyText);
    verify.disabled = Boolean(hasConfirmed || isOwn);
    verify.addEventListener("click", function () {
      if (!currentUser) { setAuthMode("login"); accountDialog.showModal(); return; }
      confirmRepair(repair.id, verify);
    });
    actions.appendChild(verify);
    footer.appendChild(actions);
    card.appendChild(footer);
    if (currentUser?.role === "admin" && !repair.isSample) {
      const adminActions = document.createElement("div");
      adminActions.className = "admin-repair-actions";
      const adminVerify = document.createElement("button");
      adminVerify.type = "button";
      adminVerify.className = "admin-verify-button";
      adminVerify.textContent = repair.adminVerified ? words().adminUnverifyGuide : words().adminVerifyGuide;
      adminVerify.addEventListener("click", function () { updateAdminVerification(repair.id, !repair.adminVerified, adminVerify); });
      adminActions.appendChild(adminVerify);
      card.appendChild(adminActions);
    }
    const commentList = Array.isArray(repair.comments) ? repair.comments : [];
    const commentDetails = document.createElement("details");
    commentDetails.className = "repair-comments";
    commentDetails.open = expandedCommentThreads.has(repair.id);
    commentDetails.addEventListener("toggle", function () {
      if (commentDetails.open) expandedCommentThreads.add(repair.id);
      else expandedCommentThreads.delete(repair.id);
    });
    const commentSummary = document.createElement("summary");
    commentSummary.textContent = words().commentsTitle + " · " + commentList.length;
    commentDetails.appendChild(commentSummary);
    const commentContent = document.createElement("div");
    commentContent.className = "repair-comments-content";
    const comments = document.createElement("div");
    comments.className = "repair-comment-list";
    if (!commentList.length) addText(comments, "p", "repair-comment-empty", words().noComments);
    commentList.forEach(function (comment) {
      const item = document.createElement("article");
      item.className = "repair-comment";
      const commentHead = document.createElement("div");
      commentHead.className = "repair-comment-head";
      addText(commentHead, "strong", "", comment.authorName);
      addText(commentHead, "time", "", formatAdminDate(comment.createdAt));
      item.appendChild(commentHead);
      addText(item, "p", "", comment.text);
      comments.appendChild(item);
    });
    commentContent.appendChild(comments);
    if (currentUser) {
      const commentForm = document.createElement("form");
      commentForm.className = "repair-comment-form";
      commentForm.dataset.commentRepair = repair.id;
      const input = document.createElement("textarea");
      input.name = "text";
      input.rows = 2;
      input.maxLength = 1000;
      input.required = true;
      input.placeholder = words().commentPlaceholder;
      commentForm.appendChild(input);
      const sendComment = document.createElement("button");
      sendComment.type = "submit";
      sendComment.className = "comment-submit";
      sendComment.textContent = words().postComment;
      commentForm.appendChild(sendComment);
      commentContent.appendChild(commentForm);
    } else {
      const loginToComment = document.createElement("button");
      loginToComment.type = "button";
      loginToComment.className = "comment-login-button";
      loginToComment.textContent = words().loginToComment;
      loginToComment.addEventListener("click", function () { setAuthMode("login"); accountDialog.showModal(); });
      commentContent.appendChild(loginToComment);
    }
    commentDetails.appendChild(commentContent);
    card.appendChild(commentDetails);
    repairList.appendChild(card);
  });
  document.getElementById("repair-empty").hidden = filtered.length > 0;
}

