async function api(path, options) {
  let response;
  try { response = await fetch(path, Object.assign({ credentials: "same-origin" }, options || {})); }
  catch (error) { throw Object.assign(new Error(words().networkError), { code: "network_error" }); }
  const payload = await response.json().catch(function () { return {}; });
  if (!response.ok) {
    if (payload.code === "maintenance") refreshLiveMaintenance();
    const error = new Error(payload.error || words().genericError);
    error.code = payload.code || "request_failed";
    error.status = response.status;
    throw error;
  }
  return payload;
}

